import { rolldown } from '../../ui/node_modules/rolldown/dist/index.mjs'
import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
const bundle = await rolldown({ input: fileURLToPath(new URL('./react-source-entry.mjs', import.meta.url)), platform: 'browser', transform: { define: { 'process.env.NODE_ENV': JSON.stringify('development') } } })
const result = await bundle.generate({ format: 'iife', name: '__hexagonReactSource', minify: true })
await bundle.close()
const code = result.output.filter(chunk => chunk.type === 'chunk').map(chunk => chunk.code).join('\n')
// Guard upgrades: source fetches must resolve the lexical adapter, never escape
// to the page's unrestricted fetch/XHR. This is a pinned build, not dynamic code.
if (/\b(?:window|globalThis|self)\.fetch\b|\bXMLHttpRequest\b|\bWebSocket\b/.test(code)) throw new Error('react-grab introduced an unguarded network path')
const guarded = `(() => {
 const hostFetch = globalThis.fetch.bind(globalThis);
 const fetch = async (input, options = {}) => {
   const url = new URL(typeof input === 'string' ? input : input.url, location.href);
   if (!['localhost','127.0.0.1','[::1]'].includes(location.hostname) || url.origin !== location.origin || url.username || url.password || (options.method || (typeof input === 'object' ? input.method : null) || 'GET').toUpperCase() !== 'GET' || !/\\.(?:[cm]?js|jsx|tsx?|map)$/.test(url.pathname)) throw new Error('source lookup unavailable');
   url.search = ''; url.hash = '';
   const response = await hostFetch(url.href, { method: 'GET', credentials: 'omit', redirect: 'error', signal: AbortSignal.timeout(650) });
   if (!response.ok || Number(response.headers.get('content-length') || 0) > 2097152) throw new Error('source lookup unavailable');
   const reader = response.body?.getReader(); if (!reader) return response;
   const chunks = []; let length = 0;
   while (true) { const part = await reader.read(); if (part.done) break; length += part.value.length; if (length > 2097152) { await reader.cancel(); throw new Error('source lookup too large'); } chunks.push(part.value); }
   return new Response(new Blob(chunks), { status: response.status, headers: response.headers });
 };
 ${code}
 globalThis.__hexagonReactSource = __hexagonReactSource;
})()`
await writeFile(new URL('./react-source.generated.mjs', import.meta.url), '// Generated by build-react-source.mjs from pinned react-grab/core 0.2.0.\nexport default '+JSON.stringify(guarded)+';\n')
console.log(`react-source-only bundle: ${Buffer.byteLength(guarded)} bytes`)
